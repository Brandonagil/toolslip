"""Hand-written look-alike tools for the tool-choice pilot.

Every real API-Bank level-3 tool gets five look-alikes. Each one does something
different from what the task needs (other quantity, other action, other input
that is not available). None of them is a shortcut that could solve the step,
so choosing one is always a wrong tool choice. Level 1 offers the first two of
every family, level 2 all five. `why_wrong` is shown in the report.
"""


def _p(**params: str) -> dict:
    return {name: {"type": spec.split(":", 1)[0], "description": spec.split(":", 1)[1].strip()}
            for name, spec in params.items()}


def _d(name: str, description: str, params: dict, why_wrong: str) -> dict:
    return {"name": name, "description": description, "input_parameters": params, "why_wrong": why_wrong}


